const GRAPHEME_SEGMENTER = new Intl.Segmenter("en", {
  granularity: "grapheme",
});

export function measureDmSans600Text(
  value: string,
  fontSize: number,
  letterSpacingEm = 0,
): number {
  const glyphs = segmentDmSans600Text(value).flatMap((grapheme) => {
    if (/\p{Extended_Pictographic}/u.test(grapheme)) {
      return [{ advance: DM_SANS_600_MAX_GLYPH_ADVANCE, id: null }];
    }

    const result: Array<{ advance: number; id: number | null }> = [];
    for (const character of grapheme) {
      const codePoint = character.codePointAt(0);
      if (codePoint === undefined) continue;
      const exactAdvance = DM_SANS_600_ADVANCE_WIDTH_BY_CODE_POINT.get(codePoint);
      if (exactAdvance !== undefined) {
        result.push({
          advance: exactAdvance,
          id: DM_SANS_600_GLYPH_ID_BY_CODE_POINT.get(codePoint) ?? null,
        });
        continue;
      }
      if (/\p{Mark}/u.test(character) || codePoint === 0x200D) continue;
      result.push({ advance: DM_SANS_600_MAX_GLYPH_ADVANCE, id: null });
    }
    return result;
  });
  const advance = glyphs.reduce((total, glyph, index) => {
    const nextGlyph = glyphs[index + 1];
    const positiveKerning = glyph.id === null || nextGlyph?.id == null
      ? 0
      : DM_SANS_600_POSITIVE_KERNING_BY_GLYPH_PAIR.get(
        glyph.id * 512 + nextGlyph.id,
      ) ?? 0;
    return total + glyph.advance + positiveKerning;
  }, 0);
  const letterSpacing = glyphs.length * fontSize * letterSpacingEm;
  return advance / DM_SANS_600_UNITS_PER_EM * fontSize + letterSpacing;
}

export function segmentDmSans600Text(value: string): string[] {
  return Array.from(
    GRAPHEME_SEGMENTER.segment(value),
    (part) => part.segment,
  );
}
