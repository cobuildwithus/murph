import type { AssistantProviderFinalResponseCompletion } from '../assistant/providers/types.js'

/**
 * Tracks the Murph-local receipt of the latest turn-scoped
 * `rawResponse/completed`. Only the receipt instant is kept, never the payload.
 * Later provider activity supersedes the completion until a newer one arrives.
 */
export interface CodexFinalResponseCompletionTracker {
  observeProviderActivity(): void
  observeRawNotification(input: {
    activeTurnId: string | null
    messageTurnId: string | null
    method: string | null
  }): void
  read(input: {
    selectedFromEarlierSampling: boolean
  }): AssistantProviderFinalResponseCompletion
}

export function createCodexFinalResponseCompletionTracker(
  readMonotonicNow: () => number = () => performance.now(),
): CodexFinalResponseCompletionTracker {
  let completedAtMonotonicMs: number | null = null
  let superseded = false
  return {
    observeProviderActivity() {
      superseded = completedAtMonotonicMs !== null
    },
    observeRawNotification({ activeTurnId, messageTurnId, method }) {
      if (
        method !== 'rawResponse/completed'
        || messageTurnId === null
        || messageTurnId !== activeTurnId
      ) {
        return
      }
      completedAtMonotonicMs = readMonotonicNow()
      superseded = false
    },
    read({ selectedFromEarlierSampling }) {
      if (completedAtMonotonicMs === null) {
        return { kind: 'unavailable' }
      }
      // A retained trailing candidate was generated by an earlier sampling.
      return superseded || selectedFromEarlierSampling
        ? { kind: 'superseded' }
        : { kind: 'observed', observedAtMonotonicMs: completedAtMonotonicMs }
    },
  }
}
